// Shared by every module; the list is frozen (shallow) so none of them can add or remove a
// built-in.
export const BUILTIN_THEMES: readonly Theme[] = Object.freeze(themes);

export function isBuiltin(id: string): boolean {
  return BUILTIN_THEMES.some((theme) => theme.id === id);
}

/** Built-ins win over custom themes with the same id; null or an unknown id returns undefined. */
export function findTheme(
  id: string | null,
  custom: readonly Theme[],
): Theme | undefined {
  if (id === null) return undefined;
  return (
    BUILTIN_THEMES.find((theme) => theme.id === id) ??
    custom.find((theme) => theme.id === id)
  );
}
