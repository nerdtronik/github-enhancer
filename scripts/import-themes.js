// Development-time tool (not part of the build): collects popular community themes (defined by
// terminal colors), keeps the permissively licensed ones that meet our readability floors, and
// writes the theme files in assets/themes plus the credits block of THIRD_PARTY_NOTICES.md. The
// kitty-themes repository is used as the data source because it records each theme's author,
// license and upstream.
// Usage: node scripts/import-themes.js
import * as esbuild from "esbuild";
import * as fs from "node:fs";

const BASE = "https://raw.githubusercontent.com/kovidgoyal/kitty-themes/master";
const OUT = "assets/themes";
const NOTICES = "THIRD_PARTY_NOTICES.md";
const START = "<!-- builtin-theme-files:start -->";
const END = "<!-- builtin-theme-files:end -->";

async function load(entry) {
  const result = await esbuild.build({ entryPoints: [entry], bundle: true, format: "esm", platform: "node", write: false, logLevel: "error" });
  const code = result.outputFiles[0].text;
  return import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
}

const kitty = await load("src/ts/features/themes/themeImport.ts");
// Files with an "upstream" field were generated by this script; the others are maintained by hand
// and are kept. The generated ones are rewritten below.
const readTheme = (file) => JSON.parse(fs.readFileSync(`${OUT}/${file}`, "utf8"));
const files = fs.readdirSync(OUT).filter((file) => file.endsWith(".json") && file !== "index.json");
const handMade = files.map(readTheme).filter((theme) => !("upstream" in theme));
const taken = new Set(handMade.map((theme) => kitty.nameKey(theme.name)));
// "default" would collide with the GitHub default row of the picker; "index" is the list file.
const reservedIds = new Set([...handMade.map((theme) => theme.id), "default", "index"]);

const text = async (url) => {
  const response = await fetch(url);
  return response.ok ? response.text() : null;
};

const index = JSON.parse(await text(`${BASE}/themes.json`));
const candidates = index.filter((entry) => kitty.PERMISSIVE.has(entry.license ?? ""));
console.log(`${index.length} themes in the index, ${candidates.length} permissively licensed`);

const converted = [];
const skipped = { duplicate: 0, unreadable: 0, download: 0 };
let cursor = 0;
async function worker() {
  while (cursor < candidates.length) {
    const entry = candidates[cursor++];
    if (taken.has(kitty.nameKey(entry.name))) {
      skipped.duplicate++;
      continue;
    }
    const conf = await text(`${BASE}/${entry.file}`).catch(() => null);
    if (!conf) {
      skipped.download++;
      continue;
    }
    const result = kitty.convertTheme(conf, { name: entry.name, license: entry.license }, reservedIds);
    if (result) converted.push(result);
    else skipped.unreadable++;
  }
}
await Promise.all(Array.from({ length: 8 }, worker));

const byId = new Map();
for (const item of converted) if (!byId.has(item.theme.id)) byId.set(item.theme.id, item);
const items = [...byId.values()].sort((a, b) => a.theme.name.localeCompare(b.theme.name));

for (const file of files) if ("upstream" in readTheme(file)) fs.rmSync(`${OUT}/${file}`);
for (const { theme, meta } of items)
  fs.writeFileSync(`${OUT}/${theme.id}.json`, `${JSON.stringify({ ...theme, license: meta.license, author: meta.author, upstream: meta.upstream })}\n`);

// The index lists every theme file (hand-made and generated), by name.
const catalog = fs
  .readdirSync(OUT)
  .filter((file) => file.endsWith(".json") && file !== "index.json")
  .map(readTheme)
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(({ id, name, mode, palette: p }) => ({ id, name, mode, colors: [p.bg, p.fg, p.accent, p.red, p.green, p.yellow, p.blue] }));
fs.writeFileSync(`${OUT}/index.json`, `${JSON.stringify(catalog)}\n`);

const rows = items.map(({ theme, meta }) => `| ${theme.name} | ${meta.author || "-"} | ${meta.license} | ${meta.upstream || "-"} |`);
const block = `${START}

## Additional built-in themes

Colors of popular community themes, converted to our palette format from their published terminal color definitions. Only themes declaring a permissive license are included; each keeps its author and upstream source. If you own one of these themes and want it removed, please open an issue.

| Theme | Author | License | Upstream |
| --- | --- | --- | --- |
${rows.join("\n")}

${END}`;
let notices = fs.readFileSync(NOTICES, "utf8");
notices = notices.includes(START)
  ? notices.replace(new RegExp(`${START}[\\s\\S]*?${END}`), () => block)
  : `${notices.trimEnd()}\n\n${block}\n`;
fs.writeFileSync(NOTICES, notices);

console.log(`wrote ${items.length} themes (${catalog.filter((c) => c.mode === "dark").length} dark, ${catalog.filter((c) => c.mode === "light").length} light); skipped`, skipped);
